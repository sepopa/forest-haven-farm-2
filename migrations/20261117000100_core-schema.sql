-- Forest Haven Farm — core schema on InsForge Postgres.
--
-- Replaces the old FastAPI/SQLAlchemy models (backend/app/models.py). Table and
-- column names are kept the same as before so a data-only dump of the old
-- database can be loaded straight in (see README → "Moving your existing data").
--
-- Security model
--   * InsForge grants anon/authenticated SELECT/INSERT/UPDATE/DELETE on every
--     public table by default, so EVERY table here has row-level security on.
--   * Being signed in is NOT enough to be an admin — anyone could create an
--     account. Admins are the user ids listed in public.admins.
--   * The public site never touches tables directly (except reading
--     content_blocks). It goes through the SECURITY DEFINER functions in the
--     next migration, which validate input exactly like the old API did.

-- ---------------------------------------------------------------------------
-- Admins
-- ---------------------------------------------------------------------------
create table if not exists public.admins (
  user_id    uuid primary key,
  username   text,
  email      text,
  created_at timestamptz not null default now()
);

alter table public.admins enable row level security;

drop policy if exists admins_read_self on public.admins;
create policy admins_read_self on public.admins
  for select to authenticated
  using (user_id = (select auth.uid()));

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------
create table if not exists public.orders (
  id              bigint generated by default as identity primary key,
  name            text not null,
  email           text not null,
  phone           text not null,
  pickup_date     date not null,
  pickup_location text not null,
  notes           text,
  policy_ack      boolean not null default false,
  status          text not null default 'new',   -- new -> confirmed -> fulfilled | cancelled
  lang            text not null default 'en',
  created_at      timestamptz not null default now(),
  -- Set when the order-emails function has sent the owner notification and
  -- the customer confirmation, so they are never sent twice.
  emails_sent_at  timestamptz,
  email_error     text
);

create index if not exists orders_email_idx on public.orders (email);
create index if not exists orders_pickup_date_idx on public.orders (pickup_date);
create index if not exists orders_created_at_idx on public.orders (created_at desc);

create table if not exists public.order_items (
  id         bigint generated by default as identity primary key,
  order_id   bigint not null references public.orders (id) on delete cascade,
  item_id    text,
  bread_item text not null,
  quantity   integer not null default 1,
  unit_price numeric(10, 2) not null default 0
);

create index if not exists order_items_order_id_idx on public.order_items (order_id);

-- ---------------------------------------------------------------------------
-- Pickup dates (rolling slots customers order against)
-- ---------------------------------------------------------------------------
create table if not exists public.pickup_dates (
  id         bigint generated by default as identity primary key,
  date       date not null unique,
  max_breads integer not null default 20,
  is_open    boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Contact form messages
-- ---------------------------------------------------------------------------
create table if not exists public.contact_messages (
  id         bigint generated by default as identity primary key,
  name       text not null,
  email      text not null,
  subject    text not null,
  message    text not null,
  status     text not null default 'new',   -- new -> replied
  created_at timestamptz not null default now()
);

create index if not exists contact_messages_created_at_idx on public.contact_messages (created_at desc);

-- ---------------------------------------------------------------------------
-- Editable site content (menu, FAQ, copy, settings, parameters…)
-- ---------------------------------------------------------------------------
create table if not exists public.content_blocks (
  id         bigint generated by default as identity primary key,
  key        text not null,
  lang       text not null default '',   -- '' for language-independent keys
  data       jsonb not null,
  updated_at timestamptz not null default now(),
  unique (key, lang)
);

-- ---------------------------------------------------------------------------
-- Page views (raw log behind the admin dashboard)
-- ---------------------------------------------------------------------------
create table if not exists public.page_views (
  id          bigint generated by default as identity primary key,
  path        text not null,
  referrer    text,
  device_type text not null default 'desktop',
  lang        text,
  visitor_id  text not null,
  created_at  timestamptz not null default now()
);

create index if not exists page_views_created_at_idx on public.page_views (created_at);
create index if not exists page_views_path_idx on public.page_views (path);

-- ---------------------------------------------------------------------------
-- Row-level security
-- ---------------------------------------------------------------------------
alter table public.orders           enable row level security;
alter table public.order_items      enable row level security;
alter table public.pickup_dates     enable row level security;
alter table public.contact_messages enable row level security;
alter table public.content_blocks   enable row level security;
alter table public.page_views       enable row level security;

-- Admins can do anything with every table directly.
do $$
declare
  t text;
begin
  foreach t in array array['orders', 'order_items', 'pickup_dates', 'contact_messages', 'content_blocks', 'page_views']
  loop
    execute format('drop policy if exists %I on public.%I', t || '_admin_all', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()))',
      t || '_admin_all', t
    );
  end loop;
end
$$;

-- Everyone can read site content (the public pages render from it).
drop policy if exists content_blocks_public_read on public.content_blocks;
create policy content_blocks_public_read on public.content_blocks
  for select to anon, authenticated
  using (true);
